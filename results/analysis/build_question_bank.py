#!/usr/bin/env python3
"""Extract QUESTIONS arrays from each mock quiz page into a single data.js
consumed by /results/analysis/index.html.

Run from repo root:
  python3 results/analysis/build_question_bank.py
"""
import re
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(ROOT, "..", ".."))

MOCKS = [
    ("diagnostic-1", "quiz/diagnostic-1/index.html"),
    ("pep-mock-1", "quiz/pep-mock-1/index.html"),
    ("pep-mock-2", "quiz/pep-mock-2/index.html"),
    ("met-mock-1", "quiz/met-mock-1/index.html"),
    ("met-mock-2", "quiz/met-mock-2/index.html"),
    ("met-mock-3", "quiz/met-mock-3/index.html"),
    ("met-mock-4", "quiz/met-mock-4/index.html"),
    ("met-mock-5", "quiz/met-mock-5/index.html"),
    ("bio-testing-paper", "quiz/bio-testing-paper/index.html"),
    ("nimhans-mock-1", "quiz/nimhans-mock-1/index.html"),
    ("pyq-mock-2", "quiz/pyq-mock-2/index.html"),
    ("rml-2020", "quiz/rml-2020/index.html"),
    ("rml-2021", "quiz/rml-2021/index.html"),
    ("rml-2022", "quiz/rml-2022/index.html"),
    ("rml-2023", "quiz/rml-2023/index.html"),
    ("rml-2024", "quiz/rml-2024/index.html"),
    ("rml-2025", "quiz/rml-2025/index.html"),
    ("ihbas-2020", "quiz/ihbas-2020/index.html"),
    ("ihbas-2024", "quiz/ihbas-2024/index.html"),
    ("amity-2023", "quiz/amity-2023/index.html"),
]

PATTERN = re.compile(r"const QUESTIONS = (\[.*?\n\]);", re.S)


def extract(path):
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    m = PATTERN.search(text)
    if not m:
        raise SystemExit(f"Could not find QUESTIONS array in {path}")
    return m.group(1)


def main():
    out_lines = [
        "// AUTO-GENERATED by results/analysis/build_question_bank.py",
        "// Re-run after editing any /quiz/<mock>/index.html question bank.",
        "window.QUESTION_BANK = {",
    ]
    for mock_id, rel in MOCKS:
        literal = extract(os.path.join(REPO, rel))
        out_lines.append(f'  "{mock_id}": {literal},')
    out_lines.append("};")
    out_path = os.path.join(ROOT, "data.js")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out_lines) + "\n")
    sizes = [(mid, extract(os.path.join(REPO, rel)).count("{ id:")) for mid, rel in MOCKS]
    for mid, n in sizes:
        print(f"  {mid}: {n} questions")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
